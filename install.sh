#!/usr/bin/env bash
# Install hdr-power as a systemd user service.
set -eu

[ "$(id -u)" -ne 0 ] || { echo "ERROR: don't run this as root (it installs a systemd --user service)."; exit 1; }
command -v kscreen-doctor >/dev/null 2>&1 || { echo "ERROR: kscreen-doctor not found — hdr-power targets KDE Plasma 6 on Wayland."; exit 1; }

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Auto-detect the mains power supply: first power supply of type "Mains" that exposes "online".
PSU=""
for d in /sys/class/power_supply/*/; do
    if [ "$(cat "${d}type" 2>/dev/null)" = "Mains" ] && [ -f "${d}online" ]; then
        PSU=$(basename "$d")
        break
    fi
done
[ -n "$PSU" ] || { echo "ERROR: no /sys/class/power_supply/<AC>/online found — this laptop doesn't expose mains state that way."; exit 1; }

# Best-effort auto-detect of the internal panel's output name (needs a live Plasma session).
OUT=$(kscreen-doctor -o 2>/dev/null | grep -oE '\beDP-[0-9]+\b' | head -1 || true)

install -Dm755 "$SRC_DIR/bin/hdr-power" "$HOME/.local/bin/hdr-power"
install -Dm644 "$SRC_DIR/systemd/hdr-power.service" "$HOME/.config/systemd/user/hdr-power.service"

# Per-machine overrides, so the unit and script stay untouched upstream.
mkdir -p "$HOME/.config/systemd/user/hdr-power.service.d"
cat > "$HOME/.config/systemd/user/hdr-power.service.d/override.conf" <<EOF
# Generated by hdr-power install.sh ($(date '+%Y-%m-%d')). Machine-specific values detected at install time.
[Service]
Environment=HDR_POWER_PSU=${PSU}
Environment=HDR_POWER_OUTPUT=${OUT:-eDP-1}
EOF

systemctl --user daemon-reload
systemctl --user enable --now hdr-power.service
# If it was already running (e.g. an update), pick up the new copy.
systemctl --user is-active --quiet hdr-power.service && systemctl --user restart hdr-power.service

echo "Installed hdr-power (PSU=${PSU}, OUTPUT=${OUT:-eDP-1})."
echo "Watch it: journalctl --user -u hdr-power -f"
